// Run after building: node --max-old-space-size=256 bench/console-navigation.mjs [preview URL]
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({executablePath: process.env.CHROMIUM ?? '/usr/bin/chromium-browser', args:['--disable-gpu']});
try {
  const page = await browser.newPage({viewport:{width:1440,height:900}, reducedMotion:'reduce'});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = process.argv[2] ?? 'https://ps5-console.rominit.pages.dev';
  await page.goto(`${base}/ps5?model=original&firmware=13.60`);
  const matches = page.locator('.console-match-link');
  const status = page.locator('#console-match-status');
  await matches.first().waitFor();
  assert.match(await status.innerText(), /Documented for Original PS5 · 13\.60[\s\S]*Relapse[\s\S]*firmware not confirmed/i);
  await matches.filter({ hasText: 'Relapse' }).click();
  await page.waitForFunction(() => document.querySelector('.console-project:target')?.textContent.includes('Relapse'));
  assert.equal(await page.locator('.console-project:target').evaluate(el => getComputedStyle(el).outlineWidth), '3px');
  await page.locator('.progress-rail a[title="Deeper access"]').click();
  assert.equal(await page.locator('#console-kernel-section').evaluate(el => el.open), true);
  await page.waitForFunction(() => document.querySelector('.progress-rail a[aria-current="location"]')?.getAttribute('title') === 'Deeper access');
  await page.selectOption('#console-installed-firmware', '14.20');
  assert.equal(await page.locator('.console-project:target').count(), 0);
  assert.doesNotMatch((await status.innerText()).split(/Lists /)[0], /Jailbreak routes/i);
  assert.equal(await matches.filter({ hasText: 'Relapse' }).count(), 0);
  await page.locator('#console-kernel-section').evaluate(el => { el.open = false; });
  await matches.filter({ hasText: 'Y2JB + Lapse' }).click();
  assert.equal(await page.locator('#console-kernel-section').evaluate(el => el.open), true);
  await page.selectOption('#console-model', 'pro');
  await page.selectOption('#console-installed-firmware', '10.40');
  assert.match(await status.innerText(), /Documented for PS5 Pro · 10\.40 \(1\)[\s\S]*Lua[\s\S]*firmware not confirmed \(\d{2,}\)/i);
  assert.equal(await page.locator('#console-models details').first().evaluate(el => el.open), false);
  assert.match(await page.locator('.console-variant', { hasText: 'PS5 Pro' }).innerText(), /Hypervisor no entry point yet/);
  await page.locator('#console-pc a', { hasText: 'ROMinit page' }).click();
  await page.waitForURL(/\/anyps5$/);
  assert.match(await page.locator('#emu-plays').innerText(), /PlayStation 5/);
  await page.goto(base + '/?category=emulator');
  await page.locator('.device-tree a', { hasText: 'AnyPS5' }).waitFor();
  await page.goto(`${base}/ps5?model=pro&firmware=10.40`);
  await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight));
  await page.locator('.header-tuck').click();
  assert.equal(await page.locator('.topbar').evaluate(el => Math.round(el.getBoundingClientRect().top)), 0);
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth);
  assert.equal(await page.locator('.progress-rail').isVisible(), false);
  await page.goto(base + '/?device=laurel_sprout');
  await page.evaluate(() => localStorage.setItem('host','linux'));
  await page.reload();
  await page.waitForSelector('.progress-rail', {state:'attached'});
  assert.ok(await page.locator('.rail-fold').count());
  assert.deepEqual(errors, []);
  console.log('Console matches, target highlight, active rail, accordion navigation, firmware gaps, emulator page link, header recall, mobile fit and shared phone rail passed.');
} finally { await browser.close(); }
